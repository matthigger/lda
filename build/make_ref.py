"""Write test/ref.js: sklearn / scipy answers for js/gauss.js to match.

Usage:
    ~/venv_ds4400/bin/python -I build/make_ref.py

Each fit case is a seeded two-class sample with probe points. LDA is
checked against sklearn's LinearDiscriminantAnalysis (lsqr solver: pooled
covariance sum_k pi_k cov_k with 1/n_k, as js/gauss.js fits it). QDA is
checked against scipy log densities of the maximum likelihood fit (1/n_k);
sklearn's QuadraticDiscriminantAnalysis uses 1/(n_k - 1) instead. Each
truth case is a model with set parameters, checked against scipy.
"""
import json
import pathlib

import numpy as np
from scipy.stats import multivariate_normal as mvn
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis

OUT = pathlib.Path(__file__).resolve().parent.parent / "test" / "ref.js"


def rand_cov(rng: np.random.Generator) -> np.ndarray:
    """A random 2 x 2 covariance with eigenvalues in [0.3, 6]."""
    t = rng.uniform(0, np.pi)
    v = np.array([np.cos(t), np.sin(t)])
    u = np.array([-v[1], v[0]])
    l1, l2 = rng.uniform(0.3, 6, size=2)
    return l1 * np.outer(v, v) + l2 * np.outer(u, u)


def log_odds(x, mu0, mu1, s0, s1, pi1):
    """log pi1 N(x; mu1, s1) - log pi0 N(x; mu0, s0)."""
    return (mvn(mu1, s1).logpdf(x) + np.log(pi1) -
            mvn(mu0, s0).logpdf(x) - np.log(1 - pi1))


def fit_case(seed: int, n0: int, n1: int) -> dict:
    """One sample, its sklearn LDA and scipy QDA log-odds on probes."""
    rng = np.random.default_rng(seed)
    mu0, mu1 = rng.uniform(-3, 3, size=(2, 2))
    x0 = rng.multivariate_normal(mu0, rand_cov(rng), size=n0)
    x1 = rng.multivariate_normal(mu1, rand_cov(rng), size=n1)
    probe = rng.uniform(-7, 7, size=(25, 2))
    x = np.vstack([x0, x1])
    y = np.r_[np.zeros(n0), np.ones(n1)]
    lda = LinearDiscriminantAnalysis(solver="lsqr").fit(x, y)
    m0, m1 = x0.mean(0), x1.mean(0)
    c0, c1 = np.cov(x0.T, bias=True), np.cov(x1.T, bias=True)
    pi1 = n1 / (n0 + n1)
    return {
        "X0": x0.tolist(), "X1": x1.tolist(), "P": probe.tolist(),
        "lda_g": lda.decision_function(probe).tolist(),
        "lda_w": lda.coef_[0].tolist(), "lda_b": float(lda.intercept_[0]),
        "qda_g": log_odds(probe, m0, m1, c0, c1, pi1).tolist(),
    }


def truth_case(seed: int) -> dict:
    """A model with set parameters and its log-odds on probes."""
    rng = np.random.default_rng(seed)
    mu0, mu1 = rng.uniform(-3, 3, size=(2, 2))
    s0, s1 = rand_cov(rng), rand_cov(rng)
    pi1 = float(rng.uniform(0.1, 0.9))
    probe = rng.uniform(-7, 7, size=(25, 2))
    fisher = np.linalg.solve(s0, mu1 - mu0)
    sym = lambda s: {"a": s[0, 0], "b": s[0, 1], "d": s[1, 1]}
    return {
        "mu0": mu0.tolist(), "mu1": mu1.tolist(), "S0": sym(s0),
        "S1": sym(s1), "pi1": pi1, "P": probe.tolist(),
        "g": log_odds(probe, mu0, mu1, s0, s1, pi1).tolist(),
        "g_shared": log_odds(probe, mu0, mu1, s0, s0, pi1).tolist(),
        "fisher": fisher.tolist(),
        "lj0": (mvn(mu0, s0).logpdf(probe) + np.log(1 - pi1)).tolist(),
        "lj1": (mvn(mu1, s1).logpdf(probe) + np.log(pi1)).tolist(),
    }


def main() -> None:
    ref = {
        "fit": [fit_case(s, n0, n1) for s, n0, n1 in
                [(1, 20, 20), (2, 7, 33), (3, 150, 60), (4, 3, 3)]],
        "truth": [truth_case(s) for s in range(10, 16)],
    }
    OUT.write_text("// sklearn / scipy answers on fixed samples: generated by"
                   " build/make_ref.py.\nconst REF = " +
                   json.dumps(ref, indent=1) + ";\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
